"use client";

import { useState } from "react";
import { Sparkles, ChevronDown, ChevronUp, Info } from "lucide-react";
import { Button } from "@/components/ui/button";
import { generateSummaryAction } from "@/actions/threads";

interface SummaryCardProps {
  threadId: string;
  summary: string | null;
  canGenerate?: boolean;
}

export function SummaryCard({ threadId, summary, canGenerate = false }: SummaryCardProps) {
  const [expanded, setExpanded] = useState(false);
  const [loading, setLoading] = useState(false);
  const [localSummary, setLocalSummary] = useState(summary);
  const [showInfo, setShowInfo] = useState(false);

  const handleGenerate = async () => {
    setLoading(true);
    const result = await generateSummaryAction(threadId);
    setLoading(false);
    if (result.success) {
      // page will revalidate; optimistic placeholder
      setLocalSummary("Summary generated. Refreshing...");
      window.location.reload();
    }
  };

  if (!localSummary && !canGenerate) return null;

  if (!localSummary && canGenerate) {
    return (
      <div className="mb-6 rounded-2xl border border-accent-200 bg-accent-50 p-5 dark:border-accent-800 dark:bg-accent-950/30">
        <div className="flex items-center justify-between gap-4">
          <div className="flex items-center gap-2">
            <Sparkles className="h-5 w-5 text-accent-600" />
            <span className="text-sm font-medium text-stone-800 dark:text-stone-200">
              AI Summary available after enough replies
            </span>
          </div>
          <Button size="sm" variant="accent" onClick={handleGenerate} disabled={loading}>
            {loading ? "Generating..." : "Generate now"}
          </Button>
        </div>
      </div>
    );
  }

  if (!localSummary) return null;

  const short = localSummary.length > 220 ? localSummary.slice(0, 220) + "..." : localSummary;
  const display = expanded ? localSummary : short;

  return (
    <div className="mb-6 rounded-2xl border border-accent-200 bg-gradient-to-br from-accent-50 to-white p-5 dark:border-accent-800 dark:from-accent-950/40 dark:to-stone-900">
      <div className="mb-3 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <Sparkles className="h-5 w-5 text-accent-600 dark:text-accent-400" />
          <h3 className="text-sm font-semibold text-stone-900 dark:text-stone-50">
            Groq summary — 30-second read
          </h3>
          <BadgeAI />
        </div>
        <button
          onClick={() => setShowInfo(!showInfo)}
          className="rounded-lg p-1 text-stone-400 hover:bg-stone-100 hover:text-stone-600 dark:hover:bg-stone-800"
          title="How this was generated"
        >
          <Info className="h-4 w-4" />
        </button>
      </div>

      {showInfo && (
        <p className="mb-3 rounded-lg bg-white/60 px-3 py-2 text-xs text-stone-500 dark:bg-stone-800/60 dark:text-stone-400">
          Generated by Groq (openai/gpt-oss-120b) from the discussion posts. This is an
          automated summary and may not capture every nuance. Always read the full thread
          for complete context.
        </p>
      )}

      <p className="text-sm leading-relaxed text-stone-700 dark:text-stone-300">{display}</p>

      {localSummary.length > 220 && (
        <button
          onClick={() => setExpanded(!expanded)}
          className="mt-3 flex items-center gap-1 text-xs font-medium text-accent-700 hover:text-accent-800 dark:text-accent-400"
        >
          {expanded ? (
            <>
              Show less <ChevronUp className="h-3.5 w-3.5" />
            </>
          ) : (
            <>
              Show full summary <ChevronDown className="h-3.5 w-3.5" />
            </>
          )}
        </button>
      )}
    </div>
  );
}

function BadgeAI() {
  return (
    <span className="rounded-full bg-accent-100 px-2 py-0.5 text-[10px] font-medium text-accent-800 dark:bg-accent-900/50 dark:text-accent-300">
      AI-generated
    </span>
  );
}
